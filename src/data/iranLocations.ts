/**
 * Returns all Iranian province names
 */
export const getAllProvinceNames = (): string[] => {
  return IRAN_PROVINCES.map((p) => p.name);
};

/**
 * Returns the list of cities for a given province name.
 * If province not found, falls back to the first province's cities or empty array.
 */
export const getCitiesForProvince = (provinceName: string): string[] => {
  const match = IRAN_PROVINCES.find(
    (p) => p.name.trim() === provinceName.trim() || p.id === provinceName.trim()
  );
  if (match) {
    return match.cities;
  }
  // Default fallback to Tehran
  return IRAN_PROVINCES[0].cities;
};

/**
 * Returns true if province exists
 */
export const isValidProvince = (provinceName: string): boolean => {
  return IRAN_PROVINCES.some((p) => p.name.trim() === provinceName.trim());
};
