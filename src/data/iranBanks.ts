export function detectIranBank(cardNumberOrPrefix: string): IranBank {
  const clean = cardNumberOrPrefix.replace(/\D/g, '');
  const prefix = clean.substring(0, 6);
  if (IRAN_BANKS[prefix]) {
    return IRAN_BANKS[prefix];
  }
  // Default TLD Transport Bank Theme
  return {
    bin: prefix,
    name: 'شبکه بانکی شتاب',
    shortName: 'بانک عضو شتاب',
    colorFrom: '#00258e',
    colorTo: '#00134e',
    textColor: '#ffffff',
    iconName: 'credit_card',
  };
}

export function validateIranianNationalId(code: string): boolean {
  const clean = code.replace(/\D/g, '');
  if (clean.length !== 10) return false;
  if (/^(\d)\1{9}$/.test(clean)) return false; // all same digits

  const check = parseInt(clean.substring(9, 10), 10);
  let sum = 0;
  for (let i = 0; i < 9; i++) {
    sum += parseInt(clean.charAt(i), 10) * (10 - i);
  }
  const rem = sum % 11;
  return (rem < 2 && check === rem) || (rem >= 2 && check === 11 - rem);
}
