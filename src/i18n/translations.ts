// Persian numeral map
const FA_NUMS = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];

export function toEnglishDigits(str: string): string {
  let res = str;
  for (let i = 0; i < 10; i++) {
    res = res.replaceAll(FA_NUMS[i], String(i));
  }
  return res;
}

// Pre-compiled list of phrases sorted by length descending
const SORTED_PHRASES_EN: [string, string][] = Object.entries(EN_DICTIONARY).sort(
  (a, b) => b[0].length - a[0].length
);

const SORTED_PHRASES_TR: [string, string][] = Object.entries(TR_DICTIONARY).sort(
  (a, b) => b[0].length - a[0].length
);

const SORTED_WORDS_TR: [string, string][] = Object.entries(WORD_TRANSLATIONS).sort(
  (a, b) => b[0].length - a[0].length
);

const SORTED_WORDS_EN: [string, string][] = Object.entries(EN_WORD_TRANSLATIONS).sort(
  (a, b) => b[0].length - a[0].length
);

/**
 * Universal translate function for any arbitrary string.
 */
export function translateString(text: string, lang: 'en' | 'tr' | 'fa'): string {
  if (lang === 'fa' || !text) return text;

  const trimmed = text.trim();
  const dict = lang === 'tr' ? TR_DICTIONARY : EN_DICTIONARY;

  // 1. Direct exact match
  if (dict[trimmed]) {
    return text.replace(trimmed, dict[trimmed]);
  }

  // Fallback to EN if TR entry is not available
  if (lang === 'tr' && EN_DICTIONARY[trimmed]) {
    return text.replace(trimmed, EN_DICTIONARY[trimmed]);
  }

  // 2. Multi-part / compound text replacement
  let output = text;

  // Convert digits
  output = toEnglishDigits(output);

  // Replace standard phrases (longer first)
  const phrases = lang === 'tr' ? SORTED_PHRASES_TR : SORTED_PHRASES_EN;
  for (const [faPhrase, translation] of phrases) {
    if (output.includes(faPhrase)) {
      output = output.replaceAll(faPhrase, translation);
    }
  }

  // Replace remaining words if Persian characters remain (using Persian word boundary check)
  if (/[\u0600-\u06FF]/.test(output)) {
    const words = lang === 'tr' ? SORTED_WORDS_TR : SORTED_WORDS_EN;

    for (const [faWord, translation] of words) {
      if (faWord.length > 1 && output.includes(faWord)) {
        const escaped = faWord.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        const regex = new RegExp(`(^|[^\\u0600-\\u06FF])${escaped}([^\\u0600-\\u06FF]|$)`, 'g');
        output = output.replace(regex, `$1${translation}$2`);
      }
    }
  }

  // Clean up any double spaces
  output = output.replace(/\s{2,}/g, ' ');

  return output;
}

/**
 * In-place DOM tree translator.
 * Safely updates nodeValue and attributes without removing or adding any DOM nodes,
 * keeping React 18 reconciliation completely happy and glitch-free.
 */
export function translateTree(root: Node, lang: 'en' | 'tr'): void {
  if (typeof document === 'undefined') return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();

  while (current) {
    const textNode = current as Text;
    const parent = textNode.parentElement;

    if (parent) {
      const tag = parent.tagName;
      if (tag !== 'SCRIPT' && tag !== 'STYLE' && tag !== 'NOSCRIPT') {
        const text = textNode.nodeValue;
        if (text && /[\u0600-\u06FF]/.test(text)) {
          if (!(textNode as any).__tld_orig) {
            (textNode as any).__tld_orig = text;
          }
          const translated = translateString(text, lang);
          if (translated !== text) {
            textNode.nodeValue = translated;
          }
        }
      }
    }

    current = walker.nextNode();
  }

  // Also translate placeholder, title, and aria-label attributes
  if (root instanceof HTMLElement) {
    const selector = 'input, textarea, button, a, [title], [aria-label]';
    const elements = root.querySelectorAll(selector);

    elements.forEach((el) => {
      translateAttributes(el as HTMLElement, lang);
    });

    if (root.matches(selector)) {
      translateAttributes(root, lang);
    }
  }
}

export function translateAttributes(el: HTMLElement, lang: 'en' | 'tr'): void {
  const placeholder = el.getAttribute('placeholder');
  if (placeholder && /[\u0600-\u06FF]/.test(placeholder)) {
    if (!el.dataset.tldOrigPlaceholder) {
      el.dataset.tldOrigPlaceholder = placeholder;
    }
    el.setAttribute('placeholder', translateString(placeholder, lang));
  }

  const title = el.getAttribute('title');
  if (title && /[\u0600-\u06FF]/.test(title)) {
    if (!el.dataset.tldOrigTitle) {
      el.dataset.tldOrigTitle = title;
    }
    el.setAttribute('title', translateString(title, lang));
  }

  const ariaLabel = el.getAttribute('aria-label');
  if (ariaLabel && /[\u0600-\u06FF]/.test(ariaLabel)) {
    if (!el.dataset.tldOrigAriaLabel) {
      el.dataset.tldOrigAriaLabel = ariaLabel;
    }
    el.setAttribute('aria-label', translateString(ariaLabel, lang));
  }
}

/**
 * Restores original Persian strings when the user switches back to Persian ('fa').
 */
export function restoreAllPersian(root: HTMLElement): void {
  if (typeof document === 'undefined') return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();

  while (current) {
    const textNode = current as Text;
    if ((textNode as any).__tld_orig !== undefined) {
      textNode.nodeValue = (textNode as any).__tld_orig;
      delete (textNode as any).__tld_orig;
    }
    current = walker.nextNode();
  }

  const elements = root.querySelectorAll<HTMLElement>(
    '[data-tld-orig-placeholder], [data-tld-orig-title], [data-tld-orig-aria-label]'
  );

  elements.forEach((el) => {
    if (el.dataset.tldOrigPlaceholder) {
      el.setAttribute('placeholder', el.dataset.tldOrigPlaceholder);
      delete el.dataset.tldOrigPlaceholder;
    }
    if (el.dataset.tldOrigTitle) {
      el.setAttribute('title', el.dataset.tldOrigTitle);
      delete el.dataset.tldOrigTitle;
    }
    if (el.dataset.tldOrigAriaLabel) {
      el.setAttribute('aria-label', el.dataset.tldOrigAriaLabel);
      delete el.dataset.tldOrigAriaLabel;
    }
  });
}
